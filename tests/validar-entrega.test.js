'use strict';
const assert = require('node:assert/strict');
const validar = require('../routes/validar-entrega');
const cantidad = (productoId,cantidad)=>({productoId,cantidad,tipoControl:'CANTIDAD'});
const serie = (productoId,numeroSerie,cantidad=1)=>({productoId,cantidad,tipoControl:'SERIE',numeroSerie});
assert.equal(validar([cantidad(1,3),cantidad(2,2)]),null);
assert.match(validar([cantidad(1,2),cantidad(1,3)]),/repetido/);
assert.equal(validar([serie(1,'A'),serie(1,'B')]),null);
assert.match(validar([serie(1,'A'),serie(1,'A')]),/más de una vez/);
assert.match(validar([serie(1,'A'),serie(2,'A')]),/más de una vez/);
assert.match(validar([serie(1,'SERIE-Á'),serie(2,'SERIE-A\u0301')]),/más de una vez/);
assert.equal(validar([serie(1,'SERIE-Á'),serie(2,'SERIE-B')]),null);
assert.match(validar([cantidad(1,1),serie(1,'B')]),/mezclar/);
assert.match(validar([serie(1,'A'),serie(1,' A ')]),/más de una vez/);
assert.match(validar([serie(1,'X'.repeat(201))]),/serie/);
assert.match(validar([serie(1,'A',2)]),/cantidad igual a 1/);
assert.match(validar([serie(1,'A',Number.MAX_SAFE_INTEGER),serie(1,'B')]),/cantidad igual a 1/);
assert.match(validar([cantidad(1,Number.MAX_SAFE_INTEGER),cantidad(1,1)]),/límite permitido/);
assert.match(validar([serie(1,'')]),/serie/);
assert.match(validar([serie(1,{ codigo: 'A' })]),/texto válida/);
assert.match(validar([serie(1,true)]),/texto válida/);
assert.match(validar([serie(1,123)]),/texto válida/);
assert.match(validar([serie(1,'A\nB')]),/serie/);
assert.match(validar([serie(1,'A\u0000B')]),/serie/);
assert.match(validar([serie(1,'A\u200bB')]),/serie/);
assert.match(validar([serie(1,'A\u202eB')]),/serie/);
assert.match(validar([serie(1,'A\u2028B')]),/serie/);
assert.match(validar([serie(1,'A\u2029B')]),/serie/);
assert.match(validar([serie(1,'A\u0085B')]),/serie/);
assert.match(validar([serie(1,'A\u00adB')]),/serie/);
assert.match(validar([serie(1,'\ufeff')]),/serie/);
assert.equal(validar([serie(1,'SERIE-ÁÑ-2026')]),null);
assert.match(validar([cantidad(1,0)]),/no válidos/);
assert.match(validar([cantidad(1,1.5)]),/no válidos/);
assert.match(validar([cantidad(1,Number.MAX_SAFE_INTEGER+1)]),/no válidos/);
assert.match(validar([null]),/no válidos/);
assert.match(validar([{}]),/no válidos/);
assert.match(validar([cantidad('1e2',1)]),/no válidos/);
assert.match(validar([cantidad(' 1 ',1)]),/no válidos/);
assert.match(validar([cantidad(1,'1.0')]),/no válidos/);
assert.match(validar([cantidad(1,'0x10')]),/no válidos/);
assert.match(validar([]),/No existen/);
assert.match(validar(Array.from({length:501},(_,i)=>cantidad(i+1,1))),/500/);
console.log('OK: validación de entregas, cantidades y series duplicadas');
